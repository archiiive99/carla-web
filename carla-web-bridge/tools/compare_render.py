@dataclass
class PaletteEntry:
    idx: int
    name: str
    rgb: tuple[int, int, int]


def _parse_carla_header(path: Path) -> list[PaletteEntry]:
    text = path.read_text()
    # Match `{R,G,B},` followed by a `// name  =  Nu` comment. Example:
    #     {128u,  64u, 128u},   // road          =   1u
    pat = re.compile(
        r"\{\s*(\d+)u?,\s*(\d+)u?,\s*(\d+)u?\s*\},\s*//\s*([A-Za-z ]+?)\s*=\s*(\d+)u"
    )
    entries = []
    for m in pat.finditer(text):
        r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3))
        name = m.group(4).strip()
        idx = int(m.group(5))
        entries.append(PaletteEntry(idx, name, (r, g, b)))
    entries.sort(key=lambda e: e.idx)
    return entries


def cmd_palette_diff(_args: argparse.Namespace) -> int:
    from src.compression.image import CITYSCAPES_PALETTE  # noqa

    if not CARLA_HEADER.exists():
        print(f"ERROR: CARLA header not found at {CARLA_HEADER}")
        return 2

    carla_entries = _parse_carla_header(CARLA_HEADER)
    print(f"CARLA header defines {len(carla_entries)} classes; bridge palette has {len(CITYSCAPES_PALETTE)}.")
    mismatches = 0
    for e in carla_entries:
        if e.idx >= len(CITYSCAPES_PALETTE):
            print(f"MISSING idx={e.idx:>2} {e.name:<14} carla_rgb={e.rgb}")
            mismatches += 1
            continue
        ours = tuple(int(x) for x in CITYSCAPES_PALETTE[e.idx])
        status = "OK  " if ours == e.rgb else "DIFF"
        if ours != e.rgb:
            mismatches += 1
        print(f"{status} idx={e.idx:>2} {e.name:<14} carla={e.rgb} ours={ours}")

    if len(CITYSCAPES_PALETTE) > len(carla_entries):
        for extra_idx in range(len(carla_entries), len(CITYSCAPES_PALETTE)):
            ours = tuple(int(x) for x in CITYSCAPES_PALETTE[extra_idx])
            print(f"EXTRA idx={extra_idx:>2} (not in header) ours={ours}")
            mismatches += 1

    print(f"\nmismatches={mismatches}")
    return 0 if mismatches == 0 else 1


