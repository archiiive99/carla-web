def _regression_failures(
    baseline_rows: list[dict[str, str]],
    new_rows: list[dict[str, str]],
    *,
    deltae_mean_tol: float = 0.0,
    deltae_p95_tol: float = 0.0,
    ssim_tol: float = 0.0,
    psnr_tol: float = 0.0,
    hist_tol: float = 0.0,
) -> list[str]:
    key_cols = [col for col in ("map", "pose", "weather", "tod", "frame", "camera_id") if baseline_rows and col in baseline_rows[0]]
    if not key_cols:
        key_cols = [col for col in ("frame", "camera_id") if new_rows and col in new_rows[0]]
    metric_cols = {
        "deltae76_mean_full_frame": ("max", deltae_mean_tol),
        "deltae76_p95_full_frame": ("max", deltae_p95_tol),
        "ssim_luma": ("min", ssim_tol),
        "psnr_db": ("min", psnr_tol),
        "hist_intersection_luma_64": ("min", hist_tol),
    }
    baseline_by_key = {tuple(row.get(col, "") for col in key_cols): row for row in baseline_rows}
    new_keys = {tuple(row.get(col, "") for col in key_cols) for row in new_rows}
    failures: list[str] = []
    for key in baseline_by_key:
        if key not in new_keys:
            failures.append(f"missing new row for key={key}")
    for row in new_rows:
        key = tuple(row.get(col, "") for col in key_cols)
        baseline = baseline_by_key.get(key)
        if baseline is None:
            failures.append(f"missing baseline row for key={key}")
            continue
        for metric, (direction, tolerance) in metric_cols.items():
            if metric not in baseline or metric not in row:
                failures.append(f"metric {metric} missing for key={key}")
                continue
            before = float(baseline[metric])
            after = float(row[metric])
            if direction == "max" and after > before + tolerance:
                failures.append(
                    f"{metric} regressed for key={key}: baseline={before:.6f} new={after:.6f} tol={tolerance:.6f}"
                )
            if direction == "min" and after < before - tolerance:
                failures.append(
                    f"{metric} regressed for key={key}: baseline={before:.6f} new={after:.6f} tol={tolerance:.6f}"
                )
    return failures


def _maybe_reexec_bridge_python() -> None:
    if os.environ.get("COMPARE_RENDER_VENV_REEXEC") == "1":
        return
    if not BRIDGE_VENV_PYTHON.exists():
        return
    try:
        current = Path(sys.executable).resolve()
        target = BRIDGE_VENV_PYTHON.resolve()
    except Exception:
        return
    if current == target:
        return
    env = os.environ.copy()
    env["COMPARE_RENDER_VENV_REEXEC"] = "1"
    result = subprocess.run(
        [str(target), str(Path(__file__).resolve()), *sys.argv[1:]],
        cwd=REPO_ROOT,
        env=env,
        check=False,
    )
    raise SystemExit(result.returncode)


