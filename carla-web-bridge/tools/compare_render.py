def _sample(im: Image.Image, stride: int = 50) -> list[tuple[int, int, int]]:
    im = im.convert("RGB")
    return list(im.getdata())[::stride]


def _stats(name: str, px: Iterable[tuple[int, int, int]]) -> dict[str, float]:
    pxl = list(px)
    n = len(pxl)
    r = [p[0] for p in pxl]
    g = [p[1] for p in pxl]
    b = [p[2] for p in pxl]
    lum = [0.299 * p[0] + 0.587 * p[1] + 0.114 * p[2] for p in pxl]
    sat = []
    for pr, pg, pb in pxl:
        _, s, _ = colorsys.rgb_to_hsv(pr / 255, pg / 255, pb / 255)
        sat.append(s)
    buckets = {
        "dark<50": sum(1 for x in lum if x < 50) / n,
        "mid50-125": sum(1 for x in lum if 50 <= x < 125) / n,
        "mid125-200": sum(1 for x in lum if 125 <= x < 200) / n,
        "bright>=200": sum(1 for x in lum if x >= 200) / n,
    }
    return {
        "name": name,
        "n": n,
        "meanR": statistics.mean(r),
        "meanG": statistics.mean(g),
        "meanB": statistics.mean(b),
        "meanLum": statistics.mean(lum),
        "stdLum": statistics.stdev(lum) if n > 1 else 0.0,
        "meanSat": statistics.mean(sat),
        **buckets,
    }


def _fmt(d: dict[str, float]) -> str:
    keys = [
        "name", "meanR", "meanG", "meanB", "meanLum", "stdLum", "meanSat",
        "dark<50", "mid50-125", "mid125-200", "bright>=200",
    ]
    out = []
    for k in keys:
        v = d[k]
        out.append(f"{k}={v:.3f}" if isinstance(v, float) else f"{k}={v}")
    return "  ".join(out)


def _delta(a: dict[str, float], b: dict[str, float]) -> str:
    keys = [
        "meanR", "meanG", "meanB", "meanLum", "stdLum", "meanSat",
        "dark<50", "mid50-125", "mid125-200", "bright>=200",
    ]
    return "  ".join(f"Δ{k}={b[k] - a[k]:+.3f}" for k in keys)


def cmd_stats(args: argparse.Namespace) -> int:
    three_path = Path(args.threejs_png)
    ue5_path = Path(args.ue5_jpg)
    three = _stats("three", _sample(Image.open(three_path)))
    ue5 = _stats("ue5", _sample(Image.open(ue5_path)))
    print(_fmt(three))
    print(_fmt(ue5))
    print("DELTA (three − ue5):", _delta(ue5, three))
    return 0


# ============================================================================
# Color-space helpers (sRGB → linear → XYZ → Lab → ΔE*76)
# ============================================================================


def _srgb_to_linear(x: float) -> float:
    x /= 255.0
    return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4


def _linear_to_xyz(r: float, g: float, b: float) -> tuple[float, float, float]:
    # D65 matrix
    X = r * 0.4124564 + g * 0.3575761 + b * 0.1804375
    Y = r * 0.2126729 + g * 0.7151522 + b * 0.0721750
    Z = r * 0.0193339 + g * 0.1191920 + b * 0.9503041
    return X, Y, Z


def _f_lab(t: float) -> float:
    delta = 6.0 / 29.0
    if t > delta ** 3:
        return t ** (1.0 / 3.0)
    return t / (3.0 * delta * delta) + 4.0 / 29.0


def rgb_to_lab(r: int, g: int, b: int) -> tuple[float, float, float]:
    rl = _srgb_to_linear(r)
    gl = _srgb_to_linear(g)
    bl = _srgb_to_linear(b)
    X, Y, Z = _linear_to_xyz(rl, gl, bl)
    # D65 white
    Xn, Yn, Zn = 0.95047, 1.00000, 1.08883
    fx = _f_lab(X / Xn)
    fy = _f_lab(Y / Yn)
    fz = _f_lab(Z / Zn)
    L = 116 * fy - 16
    a = 500 * (fx - fy)
    bb = 200 * (fy - fz)
    return L, a, bb


def delta_e_76(p: tuple[int, int, int], q: tuple[int, int, int]) -> float:
    Lp, ap, bp = rgb_to_lab(*p)
    Lq, aq, bq = rgb_to_lab(*q)
    return math.sqrt((Lp - Lq) ** 2 + (ap - aq) ** 2 + (bp - bq) ** 2)


