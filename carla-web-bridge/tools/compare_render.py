def cmd_depth_roundtrip(_args: argparse.Namespace) -> int:
    import numpy as np

    from src.compression.image import image_compressor  # noqa

    # Replicate CARLA's encode (inverse of ColorConverter.h::Depth):
    # normalized = meters / 1000
    # code = normalized * (256^3 - 1)
    # R = code & 0xff ; G = (code >> 8) & 0xff ; B = (code >> 16) & 0xff
    depths_m = [0.0, 0.5, 1.0, 5.0, 25.0, 100.0, 250.0, 500.0, 999.0, 1000.0]

    print(f"{'meters':>8}  {'encoded_BGRA':<18}  "
          f"{'decoded_norm':>13}  {'recovered_m':>12}  {'abs_err_m':>10}")
    max_err = 0.0
    for m in depths_m:
        normalized = m / 1000.0
        code = int(normalized * (256 ** 3 - 1))
        R = code & 0xFF
        G = (code >> 8) & 0xFF
        B = (code >> 16) & 0xFF

        # Build a 1x1 BGRA buffer and feed the image.py depth decode math
        # (we replicate the math here since apply_depth_colormap outputs JPEG
        # bytes, not the scalar — the math is identical to image.py:91-95).
        r_f, g_f, b_f = float(R), float(G), float(B)
        normalized_decoded = (r_f + g_f * 256.0 + b_f * 65536.0) / (256.0 ** 3 - 1.0)
        recovered_m = normalized_decoded * 1000.0
        err = abs(recovered_m - m)
        max_err = max(max_err, err)
        print(f"{m:>8.2f}  B={B:<3} G={G:<3} R={R:<3}    "
              f"{normalized_decoded:>13.8f}  {recovered_m:>12.4f}  {err:>10.2e}")

    # Quantization bound: one LSB of the R channel ≈ 1000 / (2^24 - 1) m
    lsb_m = 1000.0 / (256 ** 3 - 1)
    print(f"\ntheoretical_lsb_m={lsb_m:.3e}  max_err_m={max_err:.3e}")

    # Allow a couple of LSBs slack for float rounding
    if max_err > 3 * lsb_m:
        print("FAIL: decode error exceeds 3×LSB quantization bound")
        return 1
    print("OK: depth decode matches CARLA's ColorConverter.h::Depth within quantization.")
    return 0


