def cmd_test_pattern(args: argparse.Namespace) -> int:
    import numpy as np

    # Force backend if requested
    import os

    os.environ["JPEG_BACKEND"] = args.backend

    from src.compression.image import image_compressor  # noqa: E402

    W, H = 32, 32
    # Pattern A: solid primary colors in BGRA, 8×8 each
    # Expected RGB after decode: R=[255,0,0], G=[0,255,0], B=[0,0,255], K=[0,0,0]
    patches = {
        "red":   (0, 0, 255, 255),   # B=0 G=0 R=255
        "green": (0, 255, 0, 255),   # B=0 G=255 R=0
        "blue":  (255, 0, 0, 255),   # B=255 G=0 R=0
        "black": (0, 0, 0, 255),
        "white": (255, 255, 255, 255),
        "road":  (64, 64, 64, 255),  # neutral grey — the literal "road" test
        # These alpha values should be IGNORED (we drop alpha at RGB conversion)
        "alpha_check": (128, 200, 50, 0),  # alpha=0 must not show through
    }
    pixels: list[list[tuple[int, int, int, int]]] = []
    rows_per_patch = H // len(patches)
    names = list(patches.keys())
    for y in range(H):
        name = names[min(y // rows_per_patch, len(names) - 1)]
        pixels.append([patches[name]] * W)
    raw = _make_bgra(pixels)

    # Use quality=95 so compression noise is small enough to prove identity
    jpg = image_compressor.compress_bgra_to_jpeg(raw, W, H, quality=95)
    decoded = _decode_jpeg(jpg)
    print(f"# backend={args.backend} quality=95 input_bytes={len(raw)} "
          f"jpeg_bytes={len(jpg)} (ratio {len(raw) / max(len(jpg), 1):.2f}×)")

    # Check each patch's center pixel
    print(f"{'patch':<12}{'expected_rgb':<20}{'got_rgb':<20}{'ΔE76':>8}")
    print("-" * 60)
    max_delta = 0.0
    for i, name in enumerate(names):
        b, g, r, a = patches[name]
        expected = (r, g, b)
        y_center = i * rows_per_patch + rows_per_patch // 2
        got = tuple(int(x) for x in decoded[y_center, W // 2])
        de = delta_e_76(expected, got)
        max_delta = max(max_delta, de)
        flag = "" if de < 3.0 else "  <— drift"
        print(f"{name:<12}{str(expected):<20}{str(got):<20}{de:>8.2f}{flag}")

    # Explicit channel-swap assertion: red patch must decode to RGB with R
    # dominant, NOT B. If they ever swap, this will blow up loud.
    red_center = decoded[rows_per_patch // 2, W // 2]
    assert red_center[0] > red_center[2] + 100, (
        f"RED patch decoded as {red_center!r} — channel order is WRONG "
        f"(expected R≫B, got R={red_center[0]} B={red_center[2]})"
    )
    print(f"\nmax_ΔE76={max_delta:.2f}  channel_order=OK")
    return 0 if max_delta < 3.0 else 1


