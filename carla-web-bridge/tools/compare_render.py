#!/usr/bin/env python3
"""Color-fidelity comparison harness for the CARLA → browser pipeline.

Subcommands (all are self-contained unless noted):

    stats <three.png> <ue5.jpg>
        Legacy mode: sample both images and print per-channel / luminance
        / histogram deltas. Used by the rendering agent for quick visual
        parity checks.

    test-pattern [--backend auto|turbojpeg|pillow] [--quality 85]
        Synthetic BGRA → JPEG round-trip. Proves channel order, alpha
        handling, and chroma-subsampling behavior by encoding known
        patterns (pure R/G/B/K/W, a road-grey ramp, and a colored
        checkerboard) and checking decoded pixel values. Reports
        per-channel ΔE and ΔL.

    depth-roundtrip
        Numeric verification of the CARLA depth encoding. Picks 10 depths
        in [0, 1000 m], encodes to BGRA per CARLA's formula
        (ColorConverter.h:35-39), decodes via image.py, and asserts the
        recovered meters are within quantization tolerance.

    palette-diff
        Cross-checks src/compression/image.py's CITYSCAPES_PALETTE
        against LibCarla/.../CityScapesPalette.h by parsing the header.
        Fails non-zero if any entry drifts.

    jpeg-sweep [--quality 60,75,85,95] [--input ue5.png]
        Encodes the same reference image at several quality levels with
        both 4:2:0 and 4:4:4 chroma subsampling (Pillow), reports
        bytes and SSIM vs. the source, and writes a CSV.

    live  [--bridge ws://HOST:PORT/ws] [--carla HOST:PORT] [--frames N]
        Run the Agent-C audit driver and emit the same `report.md`
        generated by `tools/color_fidelity/run_audit.py`. The current
        live path measures raw CARLA BGRA frames against the exact server
        JPEG encoder path (wire-equivalent to the bytes sent after
        `sensor_manager._encode_camera_packet()`), then adds the offline
        JPEG / depth / palette / codec sections.

    match-frustum [--camera-id N] [--frames N]
        Pause the sim, load the browser with `?camPose=<source-camera-world-pose>`,
        capture the Three.js viewport canvas, and compare it against a shadow
        native RGB camera spawned at the same pose as the managed camera actor.
        Current scope is intentionally narrow: managed RGB camera only.

    regress --baseline old.csv --new new.csv
        Compare two CSV outputs (for example from `match-frustum`) and fail
        when any tracked metric regresses beyond the configured tolerance.

Run subcommands with -h for per-command flags.
"""
