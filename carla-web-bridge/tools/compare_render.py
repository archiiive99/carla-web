def _ssim_gray(a, b) -> float:
    # Simple single-window SSIM on luminance. Good enough for a curve;
    # skimage.metrics.structural_similarity is preferred if present.
    import numpy as np

    try:
        from skimage.metrics import structural_similarity

        return float(structural_similarity(a, b, data_range=255))
    except Exception:
        pass
    # Fallback: global MSSIM-ish
    a = a.astype("float64")
    b = b.astype("float64")
    mu_a = a.mean()
    mu_b = b.mean()
    var_a = a.var()
    var_b = b.var()
    cov = ((a - mu_a) * (b - mu_b)).mean()
    c1 = (0.01 * 255) ** 2
    c2 = (0.03 * 255) ** 2
    num = (2 * mu_a * mu_b + c1) * (2 * cov + c2)
    den = (mu_a ** 2 + mu_b ** 2 + c1) * (var_a + var_b + c2)
    return float(num / den) if den != 0 else 0.0


def cmd_jpeg_sweep(args: argparse.Namespace) -> int:
    import numpy as np

    qualities = [int(x) for x in args.quality.split(",")]
    source = Path(args.input) if args.input else None

    if source and source.exists():
        src_img = Image.open(source).convert("RGB")
    else:
        # Synthetic: road-surface speckle, white + yellow lane markings,
        # a red stop line, and a colored traffic sign patch. The yellow
        # and red are the chroma-heavy elements that expose 4:2:0
        # subsampling damage; pure grey (which the first version used)
        # cannot — that's why the SSIM curve came out flat.
        rng = np.random.default_rng(42)
        H, W = 240, 640
        asphalt = rng.integers(45, 75, size=(H, W, 3), dtype=np.uint8)
        # white lane line (center)
        asphalt[H // 2 - 3:H // 2 + 3, 100:-100, :] = 235
        # yellow solid line (upper third) — RGB ≈ (255, 210, 30)
        asphalt[H // 3 - 2:H // 3 + 2, 50:-50, 0] = 255
        asphalt[H // 3 - 2:H // 3 + 2, 50:-50, 1] = 210
        asphalt[H // 3 - 2:H // 3 + 2, 50:-50, 2] = 30
        # red stop line (lower third)
        asphalt[2 * H // 3 - 2:2 * H // 3 + 2, 100:-100, 0] = 200
        asphalt[2 * H // 3 - 2:2 * H // 3 + 2, 100:-100, 1] = 20
        asphalt[2 * H // 3 - 2:2 * H // 3 + 2, 100:-100, 2] = 20
        # traffic sign patch (upper-right) — saturated blue
        asphalt[10:40, W - 80:W - 20, 0] = 30
        asphalt[10:40, W - 80:W - 20, 1] = 90
        asphalt[10:40, W - 80:W - 20, 2] = 220
        src_img = Image.fromarray(asphalt, "RGB")

    src_arr = np.asarray(src_img, dtype=np.uint8)
    gray = src_arr.mean(axis=-1)
    rows = []
    print(f"{'quality':>7}  {'subsample':<9}  {'bytes':>8}  "
          f"{'SSIM_Y':>7}  {'ΔE_mean':>8}  {'ΔE_p99':>8}")
    for q in qualities:
        for subsampling, label in [(0, "4:4:4"), (2, "4:2:0")]:
            buf = BytesIO()
            src_img.save(buf, format="JPEG", quality=q, subsampling=subsampling)
            data = buf.getvalue()
            dec = np.asarray(Image.open(BytesIO(data)).convert("RGB"))
            ssim = _ssim_gray(gray, dec.mean(axis=-1))

            # Pixel-sampled ΔE76 on a row subset to keep this cheap
            step = 11
            flat_src = src_arr[::step, ::step].reshape(-1, 3)
            flat_dec = dec[::step, ::step].reshape(-1, 3)
            des = [
                delta_e_76(tuple(int(x) for x in s), tuple(int(x) for x in d))
                for s, d in zip(flat_src, flat_dec)
            ]
            de_mean = float(np.mean(des))
            de_p99 = float(np.percentile(des, 99))
            rows.append({
                "quality": q, "subsampling": label,
                "bytes": len(data), "ssim": ssim,
                "de_mean": de_mean, "de_p99": de_p99,
            })
            print(f"{q:>7}  {label:<9}  {len(data):>8}  "
                  f"{ssim:>7.4f}  {de_mean:>8.3f}  {de_p99:>8.3f}")

    if args.csv:
        out_path = Path(args.csv)
        with out_path.open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=[
                "quality", "subsampling", "bytes", "ssim", "de_mean", "de_p99",
            ])
            w.writeheader()
            w.writerows(rows)
        print(f"\nwrote {out_path}")

    return 0


