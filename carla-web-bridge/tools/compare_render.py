def _capture_native_shadow_frames(
    *,
    carla_host_port: str,
    source_camera_id: int,
    frames: int,
    out_dir: Path,
) -> list[dict]:
    import numpy as np

    try:
        import carla  # type: ignore
    except Exception as exc:  # pragma: no cover - live-only
        raise RuntimeError(f"carla module not importable: {exc}") from exc

    host, port = carla_host_port.split(":")
    client = carla.Client(host, int(port))
    client.set_timeout(10.0)
    world = client.get_world()
    source_actor = world.get_actor(int(source_camera_id))
    if source_actor is None:
        raise RuntimeError(f"camera actor {source_camera_id} not found in CARLA world")

    bp_lib = world.get_blueprint_library()
    cam_bp = bp_lib.find("sensor.camera.rgb")
    copied = {}
    for key in (
        "image_size_x",
        "image_size_y",
        "fov",
        "sensor_tick",
        "enable_postprocess_effects",
    ):
        value = source_actor.attributes.get(key)
        if value and cam_bp.has_attribute(key):
            cam_bp.set_attribute(key, value)
            copied[key] = value
    if cam_bp.has_attribute("role_name"):
        cam_bp.set_attribute("role_name", "compare_render_shadow")

    sensor = world.spawn_actor(cam_bp, source_actor.get_transform())
    saved: list[dict] = []
    target_frames = max(1, int(frames))

    def _on_image(img) -> None:
        if len(saved) >= target_frames:
            return
        arr = np.frombuffer(img.raw_data, dtype=np.uint8).reshape(img.height, img.width, 4)
        rgb = arr[:, :, [2, 1, 0]]
        out_path = out_dir / f"ue5_{len(saved):03d}.png"
        Image.fromarray(rgb, "RGB").save(out_path)
        saved.append(
            {
                "frame": int(img.frame),
                "timestamp": float(img.timestamp),
                "path": out_path,
                "width": int(img.width),
                "height": int(img.height),
                "copied_attrs": copied,
            }
        )

    sensor.listen(_on_image)
    try:
        settings = world.get_settings()
        deadline = time.monotonic() + max(10.0, target_frames * 2.0)
        while len(saved) < target_frames and time.monotonic() < deadline:
            if settings.synchronous_mode:
                world.tick()
            else:  # pragma: no cover - current live stack uses sync pause
                world.wait_for_tick(1.0)
            time.sleep(0.05)
        if len(saved) < target_frames:
            raise TimeoutError(
                f"captured {len(saved)}/{target_frames} native frames from source camera {source_camera_id}"
            )
    finally:
        sensor.stop()
        sensor.destroy()
    return saved


