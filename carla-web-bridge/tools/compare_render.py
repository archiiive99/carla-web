def _http_json(url: str, *, method: str = "GET", payload: dict | None = None, timeout: float = 15.0):
    data = None
    headers = {}
    if payload is not None:
        data = json.dumps(payload).encode("utf-8")
        headers["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, method=method, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def _http_post_json(url: str, payload: dict, *, timeout: float = 15.0):
    return _http_json(url, method="POST", payload=payload, timeout=timeout)


def _poll_json(url: str, predicate, *, timeout_s: float = 45.0, interval_s: float = 1.0):
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        try:
            last = _http_json(url, timeout=max(2.0, interval_s + 1.0))
            if predicate(last):
                return last
        except Exception:
            pass
        time.sleep(interval_s)
    if last is None:
        raise TimeoutError(f"Timed out polling {url}")
    raise TimeoutError(f"Timed out waiting for predicate on {url}; last={last}")


def _luma_hist_intersection(a, b, bins: int = 64) -> float:
    import numpy as np

    a_l = 0.2126 * a[..., 0] + 0.7152 * a[..., 1] + 0.0722 * a[..., 2]
    b_l = 0.2126 * b[..., 0] + 0.7152 * b[..., 1] + 0.0722 * b[..., 2]
    hist_a, _ = np.histogram(a_l, bins=bins, range=(0, 255), density=False)
    hist_b, _ = np.histogram(b_l, bins=bins, range=(0, 255), density=False)
    hist_a = hist_a.astype(np.float64)
    hist_b = hist_b.astype(np.float64)
    if hist_a.sum() == 0 or hist_b.sum() == 0:
        return 0.0
    hist_a /= hist_a.sum()
    hist_b /= hist_b.sum()
    return float(np.minimum(hist_a, hist_b).sum())


def _image_metrics(web_path: Path, ue5_path: Path) -> dict[str, float | int | str]:
    import numpy as np

    from tools.color_fidelity import color as cf_color
    from tools.color_fidelity import metrics as cf_metrics

    web = np.asarray(Image.open(web_path).convert("RGB"), dtype=np.uint8)
    ue5 = np.asarray(Image.open(ue5_path).convert("RGB"), dtype=np.uint8)
    if web.shape != ue5.shape:
        height = min(web.shape[0], ue5.shape[0])
        width = min(web.shape[1], ue5.shape[1])
        web = web[:height, :width]
        ue5 = ue5[:height, :width]

    de = cf_color.delta_e_76(web, ue5)
    per_channel = (web.astype(np.float32) - ue5.astype(np.float32)).reshape(-1, 3).mean(axis=0)
    return {
        "width": int(web.shape[1]),
        "height": int(web.shape[0]),
        "deltae76_mean_full_frame": float(de.mean()),
        "deltae76_p95_full_frame": float(np.percentile(de, 95)),
        "ssim_luma": float(cf_metrics.ssim(web, ue5)),
        "psnr_db": float(cf_metrics.psnr(web, ue5)),
        "hist_intersection_luma_64": _luma_hist_intersection(web, ue5, bins=64),
        "mean_err_r": float(per_channel[0]),
        "mean_err_g": float(per_channel[1]),
        "mean_err_b": float(per_channel[2]),
        "web_path": str(web_path),
        "ue5_path": str(ue5_path),
    }


def _target_failures(metrics: dict[str, float | int | str]) -> list[str]:
    failures: list[str] = []
    if float(metrics["deltae76_mean_full_frame"]) > 1.0:
        failures.append("deltae76_mean_full_frame>1.0")
    if float(metrics["deltae76_p95_full_frame"]) > 3.0:
        failures.append("deltae76_p95_full_frame>3.0")
    if float(metrics["ssim_luma"]) < 0.97:
        failures.append("ssim_luma<0.97")
    if float(metrics["psnr_db"]) < 32.0:
        failures.append("psnr_db<32.0")
    if float(metrics["hist_intersection_luma_64"]) < 0.92:
        failures.append("hist_intersection_luma_64<0.92")
    return failures


