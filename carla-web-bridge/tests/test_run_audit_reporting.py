def test_validate_report_structure_rejects_duplicate_and_out_of_order_sections() -> None:
    bad_report = "\n".join(
        [
            "## Summary",
            "## 10 · Limitations (audit does NOT cover)",
            "## 9 · Codec comparison (Pareto)",
            "## 10 · Limitations (audit does NOT cover)",
        ]
    )

    try:
        run_audit._validate_report_structure(bad_report)
    except ValueError as exc:
        msg = str(exc)
        assert "duplicate report sections" in msg or "out of order" in msg
    else:
        raise AssertionError("expected report structure validation to fail")


def test_build_release_bundle_marks_report_as_merged_and_orders_sections(tmp_path: Path) -> None:
    live = tmp_path / "live.md"
    codec = tmp_path / "codec.md"
    out = tmp_path / "bundle.md"
    live.write_text(
        "# Agent C\n"
        "_generated by `tools/color_fidelity/run_audit.py` at now_\n"
        "## Summary\n"
        "- [OK] 1 · Raw sensor → server JPEG (wire-equivalent)\n"
        "\n---\n\n"
        "## 1 · Raw sensor → server JPEG (wire-equivalent)\nbody1\n"
        "## 2 · Gamma decision table\nbody2\n"
        "## 3 · Channel-order test\nbody3\n"
        "## 4 · ICC profile embedded (binary-verified)\nbody4\n"
        "## 5 · Chroma subsampling sweep\nbody5\n"
        "## 6 · JPEG quality Pareto\nbody6\n"
        "## 7 · Depth decode round-trip\nbody7\n"
        "## 8 · Segmentation palette parity\nbody8\n"
        "## 10 · Limitations (audit does NOT cover)\nlimits\n"
    )
    codec.write_text(
        "# Agent C\n"
        "_generated by `tools/color_fidelity/run_audit.py` at later_\n"
        "## Summary\n"
        "- [OK] 9 · Codec comparison (Pareto)\n"
        "\n---\n\n"
        "## 9 · Codec comparison (Pareto)\ncodecbody\n"
        "## 10 · Limitations (audit does NOT cover)\notherlimits\n"
    )

    build_release_bundle.build_bundle(live, codec, out)
    text = out.read_text()

    assert "assembled from multiple verified reports" in text
    assert text.index("## 9 · Codec comparison (Pareto)") < text.index("## 10 · Limitations (audit does NOT cover)")
    assert text.count("## 10 · Limitations (audit does NOT cover)") == 1


def test_codec_compare_is_partial_when_browser_decode_is_unavailable(monkeypatch, tmp_path: Path) -> None:
    def fake_row(codec: str, variant: str, n: int = 5) -> dict:
        return {
            "codec": codec,
            "variant": variant,
            "n": n,
            "enc_ms_p50": 1.0,
            "enc_ms_p99": 2.0,
            "bytes_p50": 100,
            "bytes_p99": 100,
            "ssim": 0.99,
        }

    monkeypatch.setattr(run_audit.codec_bench, "make_reference", lambda: __import__("numpy").zeros((4, 4, 3), dtype="uint8"))
    monkeypatch.setattr(run_audit.codec_bench, "bench_jpeg", lambda *_args, **_kwargs: fake_row("JPEG", "q=85 ss=2"))
    monkeypatch.setattr(run_audit.codec_bench, "bench_webp", lambda *_args, **_kwargs: fake_row("WebP", "q=85"))
    monkeypatch.setattr(run_audit.codec_bench, "bench_avif", lambda *_args, **_kwargs: fake_row("AVIF", "q=65"))
    monkeypatch.setattr(run_audit.codec_bench, "bench_h264_keyframe", lambda *_args, **_kwargs: fake_row("H.264-key", "crf=22"))
    monkeypatch.setattr(run_audit, "_write_codec_sample", lambda out_dir, _src, codec, variant: out_dir / f"{codec}_{variant}.bin")
    monkeypatch.setattr(run_audit, "_write_pareto_plot", lambda *_args, **_kwargs: None)
    monkeypatch.setattr(run_audit, "_measure_browser_decode", lambda *_args, **_kwargs: {})

    section = run_audit.section_codec_compare(5, tmp_path)

    assert section.status == run_audit.STATUS_PARTIAL
    assert "only partially verified" in section.body_md
