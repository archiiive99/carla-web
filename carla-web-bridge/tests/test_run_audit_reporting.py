from __future__ import annotations

import json
from pathlib import Path

from tools.color_fidelity import build_release_bundle
from tools.color_fidelity import run_audit


def _ok(title: str) -> run_audit.SectionResult:
    return run_audit.SectionResult(title, "body", run_audit.STATUS_OK)


def test_main_skip_live_marks_live_and_gamma_skipped(monkeypatch, tmp_path: Path) -> None:
    monkeypatch.setattr(run_audit, "section_channel_order", lambda: _ok("3 · Channel-order test"))
    monkeypatch.setattr(run_audit, "section_icc_embed", lambda: _ok("4 · ICC profile embedded (binary-verified)"))
    monkeypatch.setattr(run_audit, "section_chroma_subsampling", lambda _out: _ok("5 · Chroma subsampling sweep"))
    monkeypatch.setattr(run_audit, "section_jpeg_quality_pareto", lambda _q, _out: _ok("6 · JPEG quality Pareto"))
    monkeypatch.setattr(run_audit, "section_depth_roundtrip", lambda: _ok("7 · Depth decode round-trip"))
    monkeypatch.setattr(run_audit, "section_seg_palette", lambda: _ok("8 · Segmentation palette parity"))

    rc = run_audit.main(["--skip-live", "--skip-codecs", "--out", str(tmp_path)])

    assert rc == 0
    report = (tmp_path / "report.md").read_text()
    assert "- [SKIPPED] 1 · Raw sensor → server JPEG (wire-equivalent)" in report
    assert "- [SKIPPED] 2 · Gamma decision table" in report
    assert "Live capture skipped by `--skip-live`." in report
    assert "Live summary unavailable in this run" in report


